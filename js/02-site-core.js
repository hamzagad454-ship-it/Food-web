  function updateLanguage() {
    isAr = currentLang === 'ar';
    document.documentElement.lang = currentLang;
    document.documentElement.dir = isAr?'rtl':'ltr';
    document.body.classList.toggle('ar', isAr);
    document.body.classList.toggle('hero-light-ar', isAr && !document.body.classList.contains('theme-dark'));
    const staticMap = staticTranslations[currentLang] || {};
    const staticReverse = {};
    Object.keys(staticTranslations).forEach(lang => Object.keys(staticTranslations[lang]).forEach(k => {staticReverse[staticTranslations[lang][k]] = k;}));
    const walker = document.createTreeWalker(document.getElementById('site'), NodeFilter.SHOW_TEXT);
    let node;
    while(node = walker.nextNode()) {
      const v = node.nodeValue.trim();
      if(staticMap[v]) node.nodeValue = node.nodeValue.replace(v, staticMap[v]);
      else if(currentLang !== 'en' && staticReverse[v] && staticMap[staticReverse[v]]) node.nodeValue = node.nodeValue.replace(v, staticMap[staticReverse[v]]);
    }
    const languageCurrent = document.getElementById('languageCurrent');
    const languageLabels = {en:'English', ar:'العربية', fr:'Français'};
    if(languageCurrent) languageCurrent.textContent = languageLabels[currentLang] || 'English';
    document.querySelectorAll('[data-lang-option]').forEach(option => {
      const active = option.dataset.langOption === currentLang;
      option.classList.toggle('is-selected', active);
      option.setAttribute('aria-selected', active?'true':'false');
    });

    document.querySelectorAll('[data-t]').forEach(e => {
      const key = e.dataset.t;
      const dict = currentLang === 'ar'?ar:currentLang === 'fr'?fr:en;
      if(dict[key] !== undefined) e.textContent = dict[key];
    });

    document.querySelectorAll('[data-ph]').forEach(e => {
      const key = e.dataset.ph;
      const dict = currentLang === 'ar'?ar:currentLang === 'fr'?fr:{};
      e.placeholder = dict[key] || enPH[key] || e.placeholder;
    });

    const detail = document.getElementById('productDetail');
    const detailIndex = detail?.hidden ? null : Number(detail.querySelector('.product-detail-shell')?.dataset.productIndex);
    renderProducts();
    if(detailIndex !== null && Number.isFinite(detailIndex)) {
      detail.innerHTML = '';
      detail.hidden = false;
      openProduct(detailIndex);
    }
    renderMobileMenu();
    renderTicker();
    if(typeof applyHeroLanguage === 'function') applyHeroLanguage();
    if(typeof window.sawaRefreshPartnerLanguage === 'function') window.sawaRefreshPartnerLanguage();
    if(typeof window.sawaRefreshLocatorLanguage === 'function') window.sawaRefreshLocatorLanguage();
    document.dispatchEvent(new CustomEvent('sawa:languagechange'));
  }

